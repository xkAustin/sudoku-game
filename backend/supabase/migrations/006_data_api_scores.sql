create or replace function public.submit_score(
  p_player_id uuid,
  p_player_name text,
  p_difficulty smallint,
  p_duration_ms integer,
  p_mistakes smallint,
  p_hints_used smallint,
  p_move_count integer,
  p_submission_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_name text := public.normalize_player_name(p_player_name);
  minimum_duration_ms integer;
  computed_score bigint;
  stored_score public.scores%rowtype;
  guard public.score_submission_guards%rowtype;
  response jsonb;
  score_changed boolean := false;
begin
  if p_player_id is null or p_submission_id is null then
    raise exception using errcode = '22023', message = 'player_id and submission_id are required';
  end if;
  if normalized_name is null
      or char_length(normalized_name) not between 1 and 20
      or normalized_name ~ '[[:cntrl:]]'
      or lower(normalized_name) = any (array['admin', 'administrator', 'moderator', 'system', 'supabase', '官方', '管理员']) then
    raise exception using errcode = '22023', message = 'player_name must contain 1 to 20 visible characters';
  end if;
  if p_difficulty is null or p_difficulty not between 1 and 6 then
    raise exception using errcode = '22023', message = 'difficulty is outside the accepted range';
  end if;
  minimum_duration_ms := (array[5000, 10000, 15000, 20000, 30000, 60000]::integer[])[p_difficulty];
  if p_duration_ms is null or p_duration_ms < minimum_duration_ms or p_duration_ms > 86400000 then
    raise exception using errcode = '22023', message = 'duration is outside the plausible range';
  end if;
  if p_mistakes is null or p_mistakes not between 0 and 2 then
    raise exception using errcode = '22023', message = 'mistakes are outside the accepted range';
  end if;
  if p_hints_used is null or p_hints_used <> 0 then
    raise exception using errcode = '22023', message = 'ranked submissions cannot use hints';
  end if;
  if p_move_count is null or p_move_count not between 8 and 10000 then
    raise exception using errcode = '22023', message = 'move_count is outside the plausible range';
  end if;

  insert into public.score_submission_guards (player_id)
  values (p_player_id)
  on conflict (player_id) do nothing;

  select *
    into guard
    from public.score_submission_guards
    where player_id = p_player_id
    for update;

  if guard.last_submission_id = p_submission_id and guard.last_response is not null then
    return guard.last_response || jsonb_build_object('duplicate', true);
  end if;

  if guard.window_started_at <= now() - interval '1 minute' then
    guard.window_started_at := now();
    guard.attempts := 0;
  end if;
  if guard.attempts >= 10 then
    raise exception using errcode = 'P0001', message = 'submission rate limit exceeded';
  end if;

  computed_score := public.calculate_ranked_score(
    p_difficulty,
    p_duration_ms,
    p_mistakes,
    p_hints_used,
    p_move_count
  );

  insert into public.scores as current_score (
    player_id,
    player_name,
    score,
    difficulty,
    duration_ms,
    mistakes,
    move_count
  )
  values (
    p_player_id,
    normalized_name,
    computed_score,
    p_difficulty,
    p_duration_ms,
    p_mistakes,
    p_move_count
  )
  on conflict (player_id) do update
    set player_name = excluded.player_name,
        score = excluded.score,
        difficulty = excluded.difficulty,
        duration_ms = excluded.duration_ms,
        mistakes = excluded.mistakes,
        move_count = excluded.move_count,
        created_at = now()
    where excluded.score > current_score.score
  returning current_score.* into stored_score;

  score_changed := found;
  if not score_changed then
    select *
      into stored_score
      from public.scores
      where player_id = p_player_id;
  end if;

  response := jsonb_build_object(
    'updated', score_changed,
    'duplicate', false,
    'player_id', stored_score.player_id,
    'player_name', stored_score.player_name,
    'score', stored_score.score,
    'difficulty', stored_score.difficulty,
    'duration_ms', stored_score.duration_ms,
    'mistakes', stored_score.mistakes,
    'move_count', stored_score.move_count,
    'created_at', stored_score.created_at
  );

  update public.score_submission_guards
    set window_started_at = guard.window_started_at,
        attempts = guard.attempts + 1,
        last_submission_id = p_submission_id,
        last_response = response,
        updated_at = now()
    where player_id = p_player_id;

  return response;
end;
$$;

create or replace function public.get_leaderboard(
  p_player_id uuid default null
)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with ranked as (
    select
      rank() over (order by score desc, created_at asc, id asc)::bigint as rank,
      player_id,
      player_name as display_name,
      score,
      created_at as submitted_at
    from public.scores
  ),
  top_rows as (
    select rank, display_name, score, submitted_at
    from ranked
    where rank <= 100
    order by rank
  ),
  self_row as (
    select rank, display_name, score, submitted_at
    from ranked
    where player_id = p_player_id
    limit 1
  )
  select jsonb_build_object(
    'entries',
    coalesce(
      (select jsonb_agg(to_jsonb(top_rows) order by rank) from top_rows),
      '[]'::jsonb
    ),
    'self_entry',
    coalesce(
      (select to_jsonb(self_row) from self_row),
      '{}'::jsonb
    )
  );
$$;

