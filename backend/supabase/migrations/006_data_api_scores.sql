create or replace function public.normalize_player_name(value text)
returns text
language sql
immutable
strict
set search_path = ''
as $$
  select regexp_replace(btrim(value), '[[:space:]]+', ' ', 'g');
$$;

create or replace function public.calculate_ranked_score(
  difficulty smallint,
  duration_ms integer,
  mistakes smallint,
  hints_used smallint,
  move_count integer
)
returns bigint
language sql
immutable
strict
set search_path = ''
as $$
  select greatest(
    1::bigint,
    (array[1000000, 2000000, 3000000, 5000000, 8000000, 13000000]::bigint[])[difficulty]
      + greatest(0, 1000000 - duration_ms)
      + greatest(0, 3 - mistakes) * 25000
      + greatest(0, 500 - move_count) * 100
      - hints_used * 100000
  );
$$;

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_id uuid not null unique,
  player_name varchar(20) not null,
  score bigint not null,
  difficulty smallint not null default 1,
  duration_ms integer not null default 0,
  mistakes smallint not null default 0,
  move_count integer not null default 0,
  created_at timestamptz not null default now(),
  constraint scores_player_name_length check (char_length(public.normalize_player_name(player_name)) between 1 and 20),
  constraint scores_player_name_visible check (player_name = public.normalize_player_name(player_name) and player_name !~ '[[:cntrl:]]'),
  constraint scores_player_name_reserved check (lower(player_name) <> all (array['admin', 'administrator', 'moderator', 'system', 'supabase', '官方', '管理员'])),
  constraint scores_score_range check (score between 1 and 20000000)
);

